"""Compare the regenerated CPU outputs with the committed ones (used by scripts/reproduce_cpu.sh).

Usage:
    python scripts/check_outputs.py [--since EPOCH_SECONDS]

Every committed results/analysis/*.csv must have the same columns and rows as in HEAD, with equal text cells and
numbers equal to within a relative tolerance of 1e-9 (absolute 1e-12). Least-squares fits and bootstrap sums differ in
their last digits between linear algebra libraries, so byte equality holds only on the platform that wrote the files.
Every committed figures/*.pdf must have been rewritten since --since. The bytes of a PDF depend on the installed
fonts, so they are not compared.
"""

import argparse
import io
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RTOL, ATOL = 1e-9, 1e-12
CSV_GLOB, PDF_GLOB = "results/analysis/*.csv", "figures/*.pdf"


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True).stdout


def committed(pattern):
    return sorted(git("ls-files", "--", pattern).decode().split())


def compare_csv(old_bytes, new_bytes):
    """('identical' | 'close' | 'different', detail) for the committed and the regenerated bytes of one CSV."""
    if old_bytes == new_bytes:
        return "identical", ""
    old, new = pd.read_csv(io.BytesIO(old_bytes)), pd.read_csv(io.BytesIO(new_bytes))
    if list(old.columns) != list(new.columns):
        return "different", f"columns changed from {list(old.columns)} to {list(new.columns)}"
    if len(old) != len(new):
        return "different", f"{len(old)} rows in HEAD, {len(new)} now"
    largest = 0.0
    for col in old.columns:
        a, b = old[col], new[col]
        if pd.api.types.is_numeric_dtype(a) and pd.api.types.is_numeric_dtype(b):
            x, y = a.to_numpy(float), b.to_numpy(float)
            ok = np.isclose(x, y, rtol=RTOL, atol=ATOL, equal_nan=True)
            both = np.isfinite(x) & np.isfinite(y)
            if both.any():
                largest = max(largest, float(np.max(np.abs(x[both] - y[both]))))
        else:
            ok = (a.isna() & b.isna()) | (a.astype(str) == b.astype(str))
            ok = np.asarray(ok)
        if not ok.all():
            row = int(np.flatnonzero(~ok)[0])
            old_value, new_value = (getattr(v, "item", lambda v=v: v)() for v in (a.iloc[row], b.iloc[row]))
            return "different", f"column {col}, row {row}: {old_value!r} in HEAD, {new_value!r} now"
    return "close", f"largest absolute difference {largest:.1e}"


def check(since=None):
    """Print one line per changed file and a summary; return the number of failures."""
    failures, counts = 0, {"identical": 0, "close": 0}
    for path in committed(CSV_GLOB):
        current = ROOT / path
        if not current.is_file():
            print(f"FAIL {path}: missing")
            failures += 1
            continue
        status, detail = compare_csv(git("show", f"HEAD:{path}"), current.read_bytes())
        if status == "different":
            print(f"FAIL {path}: {detail}")
            failures += 1
        else:
            counts[status] += 1
            if status == "close":
                print(f"close {path}: {detail}")
    pdfs = committed(PDF_GLOB)
    stale = [p for p in pdfs if not (ROOT / p).is_file() or (since is not None and (ROOT / p).stat().st_mtime < since)]
    for path in stale:
        print(f"FAIL {path}: not rewritten by this run")
    failures += len(stale)
    same_pdf = sum((ROOT / p).is_file() and (ROOT / p).read_bytes() == git("show", f"HEAD:{p}") for p in pdfs)
    print(f"CSV files: {counts['identical']} byte-identical, {counts['close']} equal within rtol {RTOL:g}, "
          f"{failures - len(stale)} different")
    print(f"PDF files: {len(pdfs) - len(stale)} of {len(pdfs)} rewritten, {same_pdf} byte-identical")
    if counts["close"] or same_pdf < len(pdfs):
        print("Files that differ only in their bytes stay modified; `git checkout -- results/analysis figures` "
              "restores the committed versions.")
    return failures


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--since", type=float, help="epoch seconds; each figure PDF must be newer")
    args = ap.parse_args(argv)
    return 1 if check(args.since) else 0


if __name__ == "__main__":
    sys.exit(main())
